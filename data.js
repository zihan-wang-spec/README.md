function fillInterest(template, interest) {
  const safe = clipInterest(interest, 18) || "你喜欢的事";
  return String(template || "").split("{interest}").join(safe);
}

function buildDirection(mainId, gapId, profile) {
  const interest = clipInterest(profile && profile.interest, 18);
  const grade = (profile && profile.grade) || "";
  const majors = (MAJOR_POOL[mainId] || []).slice();
  const bias = MAJOR_BIAS[gapId] || [];
  bias.forEach(function (m) {
    if (majors.indexOf(m) === -1) majors.push(m);
  });
  const picked = pickTwo(majors);
  const majorText = picked.join("、");

  const opener = interest
    ? fillInterest(pickOne(OPENER_WITH_INTEREST), interest)
    : pickOne(OPENER_NEUTRAL);

  const majorLine = pickOne(MAJOR_LINE).split("{majors}").join(majorText);
  const school = pickOne(SCHOOL_POOL[mainId] || SCHOOL_POOL.plan);
  const countries = pickOne(COUNTRY_POOL[mainId] || COUNTRY_POOL.plan);
  const countryLine = pickOne(COUNTRY_LINE).split("{countries}").join(countries);
  const gradeHints = GRADE_HINT[grade] || ["按自己的节奏慢慢来就好，先当参考。"];
  const gradeLine = fillInterest(pickOne(gradeHints), interest);

  return [opener, majorLine, school, countryLine, gradeLine].join("");
}

function buildGapAdvice(mainId, gapId, profile) {
  const interest = clipInterest(profile && profile.interest, 18);
  let action = fillInterest(
    pickOne(GAP_ACTION_POOL[gapId] || GAP_ACTION_POOL.plan),
    interest
  );
  let benefit = fillInterest(
    pickOne(GAP_BENEFIT[gapId] || GAP_BENEFIT.plan),
    interest
  );
  if (!/[。！？]$/.test(action)) action += "。";
  if (!/[。！？]$/.test(benefit)) benefit += "。";
  return action + benefit;
}


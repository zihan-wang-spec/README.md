/* 短句零件池：结果页按主类型 / 待补 / 年级 / 兴趣现场拼装 */
function pickOne(list) {
  if (!list || !list.length) return "";
  return list[Math.floor(Math.random() * list.length)];
}

function pickTwo(list) {
  if (!list || !list.length) return [];
  if (list.length === 1) return [list[0]];
  const copy = list.slice();
  const a = copy.splice(Math.floor(Math.random() * copy.length), 1)[0];
  const b = copy[Math.floor(Math.random() * copy.length)];
  return [a, b];
}

function clipInterest(text, maxLen) {
  const raw = String(text || "").replace(/\s+/g, " ").trim();
  if (!raw) return "";
  const limit = maxLen || 24;
  return raw.length > limit ? raw.slice(0, limit) + "…" : raw;
}

